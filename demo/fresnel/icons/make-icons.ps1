# Draws the demo plugin glyphs (32x32 PNG) and writes them as Pascal byte arrays
# into ..\plugins\common\demoglyphs.inc, so the plugin libraries carry their glyphs
# without resource files. Run from any folder: .\make-icons.ps1
Add-Type -AssemblyName System.Drawing

function New-Icon([string]$Name, [string]$Tile, [scriptblock]$Draw) {
  $bmp = New-Object System.Drawing.Bitmap 32, 32
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.SmoothingMode = 'AntiAlias'
  $g.Clear([System.Drawing.Color]::Transparent)
  $brush = New-Object System.Drawing.SolidBrush ([System.Drawing.ColorTranslator]::FromHtml($Tile))
  $g.FillRectangle($brush, 2, 2, 28, 28)
  $white = [System.Drawing.Brushes]::White
  $pen = New-Object System.Drawing.Pen ([System.Drawing.Color]::White), 2.5
  & $Draw $g $white $pen
  $bmp.Save((Join-Path $PSScriptRoot "$Name.png"), [System.Drawing.Imaging.ImageFormat]::Png)
  $g.Dispose(); $bmp.Dispose()
}

New-Icon 'hello'  '#33658a' { param($g,$w,$p) $g.FillEllipse($w,6,7,20,14); $g.FillPolygon($w,@((New-Object Drawing.Point 10,18),(New-Object Drawing.Point 8,26),(New-Object Drawing.Point 16,19))) }
New-Icon 'note'   '#8a5a33' { param($g,$w,$p) $g.FillRectangle($w,8,6,16,20); $g.DrawLine((New-Object Drawing.Pen ([Drawing.ColorTranslator]::FromHtml('#8a5a33')),2),11,12,21,12); $g.DrawLine((New-Object Drawing.Pen ([Drawing.ColorTranslator]::FromHtml('#8a5a33')),2),11,17,21,17); $g.DrawLine((New-Object Drawing.Pen ([Drawing.ColorTranslator]::FromHtml('#8a5a33')),2),11,22,17,22) }
New-Icon 'flag'   '#a33a3a' { param($g,$w,$p) $g.DrawLine($p,9,6,9,26); $g.FillPolygon($w,@((New-Object Drawing.Point 10,7),(New-Object Drawing.Point 24,11),(New-Object Drawing.Point 10,16))) }
New-Icon 'float'  '#3d7a5a' { param($g,$w,$p) $g.DrawLine($p,6,22,26,22); $g.FillRectangle($w,7,13,10,6); $g.DrawRectangle($p,17,13,8,6) }

$out = Join-Path $PSScriptRoot '..\plugins\common\demoglyphs.inc'
$lines = @('{ Generated by demo\fresnel\icons\make-icons.ps1. Do not edit. }', 'const')
foreach ($name in 'hello','note','flag','float') {
  $bytes = [IO.File]::ReadAllBytes((Join-Path $PSScriptRoot "$name.png"))
  $lines += "  cGlyph_$name" + ": array[0.." + ($bytes.Length-1) + "] of Byte = ("
  for ($i = 0; $i -lt $bytes.Length; $i += 20) {
    $chunk = $bytes[$i..([Math]::Min($i+19,$bytes.Length-1))] | ForEach-Object { '$' + $_.ToString('X2') }
    $sep = $(if ($i + 20 -lt $bytes.Length) { ',' } else { '' })
    $lines += '    ' + ($chunk -join ',') + $sep
  }
  $lines += '  );'
}
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
Set-Content -Path $out -Value $lines -Encoding ASCII
"Wrote $out"
